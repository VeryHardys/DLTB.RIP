param(
    [string]$FontsDir = (Join-Path $PSScriptRoot '..\fonts'),
    [string]$Output = (Join-Path $PSScriptRoot '..\bytes.hpp')
)
# Generates bytes.hpp (fonts embedded as C arrays) from the free fonts in fonts\:
#   font_medium_binary  <- Manrope-Medium.ttf     (SIL OFL 1.1)
#   font_heavy_binary   <- Manrope-ExtraBold.ttf  (SIL OFL 1.1)
#   font_awesome_binary <- fa-solid-900.ttf        (Font Awesome 5 Free, SIL OFL 1.1)
$ErrorActionPreference = 'Stop'
$map = [ordered]@{
    'font_medium_binary'  = 'Manrope-Medium.ttf'
    'font_heavy_binary'   = 'Manrope-ExtraBold.ttf'
    'font_awesome_binary' = 'fa-solid-900.ttf'
}
$sb = New-Object Text.StringBuilder
[void]$sb.AppendLine('#pragma once')
[void]$sb.AppendLine('// Generated by tools\Embed-Fonts.ps1 - do not edit by hand.')
[void]$sb.AppendLine('// Fonts: Manrope (c) The Manrope Project Authors, Font Awesome 5 Free (c) Fonticons, Inc.')
[void]$sb.AppendLine('// Both are licensed under the SIL Open Font License 1.1 - see fonts\.')
foreach ($name in $map.Keys) {
    $bytes = [IO.File]::ReadAllBytes((Join-Path $FontsDir $map[$name]))
    [void]$sb.AppendLine('')
    [void]$sb.AppendLine("// $($map[$name]) ($($bytes.Length) bytes)")
    [void]$sb.Append("unsigned char $name[] = {")
    for ($i = 0; $i -lt $bytes.Length; $i++) {
        if ($i % 24 -eq 0) { [void]$sb.Append("`r`n    ") }
        [void]$sb.Append('0x').Append($bytes[$i].ToString('X2')).Append(',')
    }
    [void]$sb.AppendLine("`r`n};")
}
[IO.File]::WriteAllText($Output, $sb.ToString(), (New-Object Text.UTF8Encoding($false)))
Write-Host "Wrote $Output"
